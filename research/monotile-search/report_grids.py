"""Append the stage-2 (other grids) section to RESULTS.md from results/*.json."""
import json
import os

import grids as G

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = '<!-- stage2: generated by report_grids.py -->'

ORDER = ['kite', 'square', 'hex', 'tri', 'drafter', 'floret', 'cairo', 'prismatic', 'rhomb', 'tetrakis', 'triakis']
OEIS = {'square': 'A000105', 'hex': 'A000228', 'tri': 'A000577', 'kite': 'A057786', 'drafter': 'A197462',
        'rhomb': 'A197459', 'tetrakis': 'A197465', 'triakis': 'A057784', 'cairo': 'A159866',
        'prismatic': 'A197156', 'floret': 'A197159'}
FRONTIER = ['tetrakis', 'drafter', 'floret', 'triakis', 'rhomb', 'cairo', 'prismatic']
# OEIS terms (fetched 1 Nov 2026 from oeis.org; tetrakis, drafter, floret, prismatic pages read
# directly, the others from test_engine.py)
OEIS_TERMS = {
    'tetrakis': [1, 2, 2, 6, 8, 22, 42, 112, 252, 650, 1584, 4091, 10369, 26938, 69651, 182116],
    'drafter': [1, 3, 3, 9, 14, 38, 74, 185, 414, 1026, 2440, 6077, 14926, 37454, 93749, 237035],
    'floret': [1, 3, 8, 25, 80, 291, 1036, 3875, 14561, 55624],
    'prismatic': [1, 3, 5, 20, 56, 225, 819, 3333, 13336],
    'rhomb': [1, 1, 3, 4, 12, 27, 78, 208, 635, 1859],
    'triakis': [1, 2, 2, 4, 4, 10, 13, 29, 47, 100, 181],
    'cairo': [1, 2, 5, 17, 55, 206, 781, 3099],
}
GEOM = {
    'tetrakis': '45 deg (p4m; cell angles 45-45-90; edges in 4 directions, 0/45/90/135 deg)',
    'cairo': '90/120 deg (p4g; angles 120,120,90,120,90; no 45 deg edges)',
    'prismatic': '60/90 deg (cmm; angles 90,90,120,120,120 (house))',
    'drafter': '30/60 deg (p6m; 30-60-90 triangles; 12 edge directions)',
    'floret': '60 deg (p6, chiral; angles 60,120,120,120,120)',
    'triakis': '30/60 deg (p6m; 30-30-120 triangles)',
    'rhomb': '60 deg (p6m; 60-120 rhombs)',
}


def main():
    L = [MARK, '', '# Stage 2: the other Laves grids', '',
         'Engine: `grids.py` (exact grid geometry in Q(sqrt3), symmetry groups found by search and '
         'checked cell by cell), `engine.py` (enumeration, disc-cover / torus / Heesch SAT tests on any '
         'grid), `verify.py` (independent re-checks), `sieve.py` (runs a grid), `regress.py`, '
         '`test_engine.py`.', '',
         'Outcomes per shape: **STUCK** (some disc cannot be covered: proof it does not tile on the grid), '
         '**PERIODIC** (tiles a torus: proof it tiles periodically), **OPEN** (neither, within the caps). '
         'OPEN means only "OPEN after caps X". It is never a claim of aperiodicity.', '',
         'Caps: stage 0 = torus <= 12 tiles per fundamental domain, disc R <= 6; every shape still OPEN '
         'is re-tested (dovetailing) at torus <= 24 / R <= 8, then torus <= 48 / R <= 12 (only the new '
         'part of the budget is searched). Disc radius unit: a length such that a unit disc holds as many '
         'cells as on the kite grid (where it is the hexagon spacing), so R means the same "number of '
         'cells" on every grid.', '',
         '## Grids', '', '| grid | Laves | cell | cell types / lattice cell | point symmetries | OEIS |',
         '|---|---|---|---|---|---|']
    for nm in ORDER:
        g = G.get(nm)
        L.append(f'| {nm} | {g.laves} | {g.cellname} | {g.m} | {len(g.ops)}{" (chiral, p6)" if g.chiral else ""} '
                 f'| {OEIS[nm]} |')
    L += ['', 'All grids pass exact checks: prototile areas add up to the lattice cell (exactly), every edge '
          'is shared by exactly two cells with opposite orientation, cells are interior-disjoint, and every '
          'symmetry maps every cell of a window vertex-for-vertex onto the cell its integer table predicts.', '']
    reg = json.load(open(os.path.join(HERE, 'results', 'regression.json'))) \
        if os.path.exists(os.path.join(HERE, 'results', 'regression.json')) else {}
    if 'kite' in reg:
        L += ['## Regression 1: kite grid vs the stage-1 polykite code', '',
              '| n | shapes (old / new) | identical shape lists | class disagreements | min-period disagreements '
              '| failing-radius disagreements | OPEN |', '|---|---|---|---|---|---|---|']
        for n, r in sorted(reg['kite'].items(), key=lambda x: int(x[0])):
            L.append(f"| {n} | {r['shapes_old']} / {r['shapes_new']} | {'yes' if r['identical_shape_lists'] else 'NO'} "
                     f"| {r['class_disagreements']} | {r['min_period_disagreements']} | {r['fail_radius_disagreements']} "
                     f"| {', '.join(r['open_shapes']) or '-'} |")
        L.append('')
    if 'myers' in reg:
        L += ['## Regression 2: Myers\' tables (polyominoes, polyhexes, polyiamonds, polykites)', '',
              '| grid | n | Myers: shapes / non-tilers (incl. holes) | ours: shapes / STUCK / PERIODIC / OPEN | match |',
              '|---|---|---|---|---|']
        for k, r in reg['myers'].items():
            c = r['ours']
            L.append(f"| {r['grid']} | {r['n']} | {r['myers_shapes']} / {r['myers_nontilers']} | {r['ours_shapes']} / "
                     f"{c.get('STUCK', 0)} / {c.get('PERIODIC', 0)} / {c.get('OPEN', 0)} | {'yes' if r['match'] else 'NO'} |")
        L.append('')
    L += ['## Frontier grids', '']
    for nm in FRONTIER:
        p = os.path.join(HERE, 'results', f'{nm}.json')
        if not os.path.exists(p):
            continue
        res = json.load(open(p))
        g = G.get(nm)
        L += [f'### {nm} {g.laves} ({g.cellname}s)', '']
        if g.notes:
            L += [g.notes + '.', '']
        if g.chiral:
            L += ['The floret grid is chiral (symmetry group p6): a mirror image of a polyform lies on the mirror '
                  'grid, never on this one (no off-group congruent copies were found), so placements use the 6 '
                  'rotations only. This is the on-grid convention used throughout (as in Myers\' tables).', '']
        L += ['Geometry: ' + GEOM[nm] + '.', '']
        L += ['| n | free (OEIS ' + OEIS[nm] + ') | STUCK | PERIODIC | OPEN at 12/R6 | OPEN after dovetail | '
              'most tiles per period needed | largest failing R | certificates re-checked | wall time |',
              '|---|---|---|---|---|---|---|---|---|---|']
        for n, r in sorted(res.items(), key=lambda x: int(x[0])):
            c = r['counts']
            st = r['stages']
            o0 = st[0]['open_after']
            last = st[-1]
            caps = f"{c.get('OPEN', 0)} (caps {last['tcap']}/R{last['rcap']:g})"
            ver = f"{r['verified']} ({r['verify_mode']}), {len(r['verify_failures'])} failed"
            tt = OEIS_TERMS.get(nm, [])
            oe = (' (=)' if r['free'] == tt[int(n) - 1] else f' (OEIS {tt[int(n) - 1]}: MISMATCH)') if int(n) <= len(tt) else ''
            L.append(f"| {n} | {r['free']}{oe} | {c.get('STUCK', 0)} | {c.get('PERIODIC', 0)} | {o0} | {caps} | "
                     f"{r['max_tiles_needed']} | {r['max_fail_R']} | {ver} | {r['wall_time']}s |")
        L.append('')
        for n, r in sorted(res.items(), key=lambda x: int(x[0])):
            for oid in r['open_ids']:
                L += [f'**{oid}** ({n} {g.cellname}s): OPEN after the caps above.', '',
                      f'![{oid}](open/{oid}.png)', '']
    L += ['## Which grids host 45 deg and which 60 deg geometry', '',
          '* **45 deg (square symmetry):** only **tetrakis** [4.8^2]* has 45 deg corners and edges in the four '
          'directions 0/45/90/135 deg, i.e. the eight edge directions of the Ammann-Beenker (silver) tiling. '
          'Its symmetry group is p4m, so on-grid copies use 8 orientations (rotations by 90 deg, mirrors); a '
          '45 deg rotation is *not* a grid symmetry. Axis edges have integer length and diagonal edges length '
          'k*sqrt2/2, so lengths live in Z[sqrt2]/2, the ring of the silver mean. The square grid (polyominoes) '
          'has 90 deg only.',
          '* **90/120 deg, 4-fold:** Cairo (p4g) and prismatic pentagonal (cmm) mix right angles with 120 deg '
          'corners; neither has 45 deg edges.',
          '* **60 deg (hexagonal):** tri, hex, rhomb, kite, triakis, floret (p6, chiral) and drafter. The drafter '
          'grid is the finest: 30-60-90 triangles, 12 edge directions, edge lengths 1, sqrt3, 2 (in the kite '
          'frame), and every polykite (hat, turtle) is a polydrafter of twice the size. Lengths live in Z[sqrt3]; '
          'the golden hat family and the hexagonal bronze-mean tiling are both hexagonal-orientation tilings.', '']
    fpd = os.path.join(HERE, 'results', 'fingerprints')
    if os.path.isdir(fpd):
        L += ['## Frequency fingerprints (weak evidence)', '',
              'Largest SAT-covered disc per shape; orientation classes counted over all tiles and over tiles '
              'wholly inside radius R-2. Ratio = majority : minority handedness (non-mirror vs mirror forms). '
              'Targets: phi=1.618, phi^2=2.618, phi^4=6.854, silver=2.414, silver^2=5.828, bronze=3.303, '
              'bronze^2=10.908. SAT covers are not hierarchical (the solver returns *some* cover), so a ratio '
              'here is weak evidence at best; for the hat, substitution patches give 6.854 (FORMULATION.md 8).', '',
              '| grid | shape | R | tiles (inner) | majority : minority, all | inner | nearest target (inner) |',
              '|---|---|---|---|---|---|---|']
        for fn in sorted(os.listdir(fpd)):
            d = json.load(open(os.path.join(fpd, fn)))
            for p in d['patches']:
                if not p.get('all'):
                    L.append(f"| {d['grid']} | {fn[len(d['grid']) + 1:-5]} | {p['R']:g} | not covered | | | |")
                    continue
                a, i = p['all'], p['inner']
                near = ', '.join(f"{k} ({e * 100:.1f}%)" for k, e in i.get('nearest', []))
                L.append(f"| {d['grid']} | {fn[len(d['grid']) + 1:-5]} | {p['R']:g} | {a['tiles']} ({i['tiles']}) | "
                         f"{a.get('majority_to_minority_handedness', '-')} | {i.get('majority_to_minority_handedness', '-')} | {near} |")
            if d.get('achiral'):
                L.append(f"| {d['grid']} | (shape is achiral: handedness ratio undefined) | | | | | |")
        L.append('')
    text = open(os.path.join(HERE, 'RESULTS.md')).read()
    if MARK in text:
        text = text[:text.index(MARK)]
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write(text.rstrip() + '\n\n' + '\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
